def parse_gd_words(json_path):
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    return data

def merge_words(gd_words, new_words):
    all_words = {}
    for w in gd_words:
        word_lower = w['word'].lower()
        all_words[word_lower] = w
    for word, meaning in new_words:
        word_lower = word.lower()
        if word_lower in all_words:
            existing = all_words[word_lower]['meaning']
            if meaning not in existing:
                all_words[word_lower]['meaning'] = existing + ' / ' + meaning
        else:
            all_words[word_lower] = {'word': word, 'phonetic': '', 'meaning': meaning}
    result = sorted(all_words.values(), key=lambda x: x['word'].lower())
    return result

def generate_markdown(words, output_path):
    lines = []
    lines.append('# 深圳中考英语新课标2000词词汇表\n')
    lines.append('> 依据《义务教育英语课程标准》（2022年版），包含约1600个基础词汇及约400个新增词汇\n')
    lines.append('> 参考来源：广东省初中学业水平考试英语词汇表、中考英语新课标词汇表\n\n')

    current_letter = ''
    for w in words:
        letter = w['word'][0].upper()
        if letter != current_letter:
            current_letter = letter
            lines.append(f'## {letter}\n')
        phonetic = f'*{w["phonetic"]}*' if w.get('phonetic') else ''
        meaning = w['meaning'].replace('<br>', '\n').replace('</br>', '').replace('<i>', '*').replace('</i>', '*')
        entry = f'- **{w["word"]}** {phonetic} {meaning}\n'
        lines.append(entry)

    with open(output_path, 'w', encoding='utf-8') as f:
        f.writelines(lines)
    return len(words)

